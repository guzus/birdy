#!/usr/bin/env node
//
// Generates internal/xapi/features_gen.go from bird's feature builders.
//
//   node scripts/gen-features.mjs | gofmt > internal/xapi/features_gen.go
//
// The gofmt step matters: this script emits unaligned struct literals, so
// piping it straight to the file leaves a diff that `gofmt -l` flags.
//
// X requires a large, exact set of feature flags on every GraphQL call and
// rejects the request when one it expects is missing. Those sets are long and
// change with X's web client, so they are generated from bird's copy rather
// than transcribed by hand.
//
// Regenerate after bumping the vendored bird package.

import { pathToFileURL } from 'node:url';
import path from 'node:path';
import { readFileSync } from 'node:fs';

const birdLib =
  process.env.BIRD_LIB ??
  path.resolve('third_party/@steipete/bird/dist/lib/twitter-client-features.js');

const f = await import(pathToFileURL(birdLib).href);

// Go identifier -> the bird builder that produces it.
const SETS = {
  searchFeatures: 'buildSearchFeatures',
  userTweetsFeatures: 'buildUserTweetsFeatures',
  homeTimelineFeatures: 'buildHomeTimelineFeatures',
  timelineFeatures: 'buildTimelineFeatures',
  likesFeatures: 'buildLikesFeatures',
  bookmarksFeatures: 'buildBookmarksFeatures',
  followingFeatures: 'buildFollowingFeatures',
  tweetCreateFeatures: 'buildTweetCreateFeatures',
  listsFeatures: 'buildListsFeatures',
  exploreFeatures: 'buildExploreFeatures',
  articleFeatures: 'buildArticleFeatures',
};

// UserByScreenName's flags are inline in bird's user-lookup module rather than
// exposed as a builder, so they are declared here.
const USER_BY_SCREEN_NAME = {
  hidden_profile_subscriptions_enabled: true,
  hidden_profile_likes_enabled: true,
  rweb_tipjar_consumption_enabled: true,
  responsive_web_graphql_exclude_directive_enabled: true,
  verified_phone_label_enabled: false,
  subscriptions_verification_info_is_identity_verified_enabled: true,
  subscriptions_verification_info_verified_since_enabled: true,
  highlights_tweets_tab_ui_enabled: true,
  responsive_web_twitter_article_notes_tab_enabled: true,
  subscriptions_feature_can_gift_premium: true,
  creator_subscriptions_tweet_preview_api_enabled: true,
  responsive_web_graphql_skip_user_profile_image_extensions_enabled: false,
  responsive_web_graphql_timeline_navigation_enabled: true,
  blue_business_profile_image_shape_enabled: true,
};

function emit(name, obj) {
  const keys = Object.keys(obj).sort();
  const width = Math.max(...keys.map((k) => k.length)) + 2;
  const lines = keys.map((k) => {
    const quoted = `"${k}":`;
    return `\t${quoted.padEnd(width + 1)} ${obj[k]},`;
  });
  return `var ${name} = map[string]bool{\n${lines.join('\n')}\n}\n`;
}

// Persisted-query hashes. query-ids.json is refreshed by bird's updater; the
// constants module carries fallbacks for when a hash rotates. Both are emitted
// so the Go client can try each in turn.
const OPERATIONS = [
  'TweetDetail', 'SearchTimeline', 'UserTweets', 'HomeTimeline',
  'HomeLatestTimeline', 'Likes', 'Bookmarks', 'ListLatestTweetsTimeline',
  'Following', 'Followers',
  // Mutations. CreateFriendship/DestroyFriendship are the GraphQL fallback
  // for follow/unfollow; the REST path is tried first.
  'CreateTweet', 'CreateFriendship', 'DestroyFriendship', 'DeleteBookmark',
  'ListOwnerships', 'ListMemberships', 'Favoriters', 'Retweeters',
  'GenericTimelineById',
  // Carries no feature set of its own; only its hash is needed.
  'AboutAccountQuery',
  // bird's read-time fallback for an article whose TweetDetail response gave a
  // title but no body. The hash exists only in FALLBACK_QUERY_IDS.
  'UserArticlesTweets',
];

function loadQueryIds() {
  const dir = path.dirname(birdLib);
  const current = JSON.parse(readFileSync(path.join(dir, 'query-ids.json'), 'utf8'));
  const constants = readFileSync(path.join(dir, 'twitter-client-constants.js'), 'utf8');

  const fallbacks = {};
  const block = constants.match(/FALLBACK_QUERY_IDS\s*=\s*\{([\s\S]*?)\n\}/);
  if (block) {
    for (const m of block[1].matchAll(/(\w+):\s*'([^']+)'/g)) fallbacks[m[1]] = m[2];
  }

  const out = {};
  for (const op of OPERATIONS) {
    const ids = [];
    for (const id of [current[op], fallbacks[op]]) {
      if (id && !ids.includes(id)) ids.push(id);
    }
    if (ids.length === 0) throw new Error(`no query id found for ${op}`);
    out[op] = ids;
  }
  // Not a builder-backed operation; hashes are inline in bird's user-lookup.
  out.UserByScreenName = ['xc8f1g7BYqr6VTzTbvNlGw', 'qW5u-DAuXpMEG0zA1F7UGQ', 'sLVLhk0bGj3MVFEKTdax1w'];
  return out;
}

function emitQueryIDs(ids) {
  const lines = Object.entries(ids).map(
    ([op, list]) => `\t"${op}": {${list.map((i) => `"${i}"`).join(', ')}},`,
  );
  return `// queryIDs are tried in order; X serves a 404 for a rotated hash.\nvar queryIDs = map[string][]string{\n${lines.join('\n')}\n}\n`;
}

const out = [];
out.push('// Code generated by scripts/gen-features.mjs. DO NOT EDIT.');
out.push('//');
out.push("// Source: bird's twitter-client-features.js. X rejects a GraphQL call when a");
out.push('// feature flag it expects is absent, so these mirror the web client exactly.');
out.push('// Regenerate with: node scripts/gen-features.mjs | gofmt > internal/xapi/features_gen.go');
out.push('');
out.push('package xapi');
out.push('');

for (const [goName, builder] of Object.entries(SETS)) {
  if (typeof f[builder] !== 'function') {
    throw new Error(`bird does not export ${builder}`);
  }
  out.push(emit(goName, f[builder]()));
}
out.push(emit('userByScreenNameFeatures', USER_BY_SCREEN_NAME));
out.push(emitQueryIDs(loadQueryIds()));

process.stdout.write(out.join('\n'));
